  function bare(s) {
    var out = '';
    for (var i = 0; i < s.length; i++) {
      var c = s.charAt(i);
      out += TONE_MARKS[c] ? baseOf(c) : c;
    }
    return out;
  }
  var BASE = 'aeiouü';
  var TONED = 'āáǎàēéěèīíǐìōóǒòūúǔùǖǘǚǜ';
  function baseOf(c) {
    var i = TONED.indexOf(c);
    if (i < 0) return c;
    return BASE.charAt(Math.floor(i / 4));
  }

